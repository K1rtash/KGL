#ifndef KGL_VECTOR
#define KGL_VECTOR

struct KGL_Vec2d {
    double x, y;
};

struct KGL_Vec2f {
    float x, y;
};

struct KGL_Vec3d {
    double x, y, z;
};

struct KGL_Vec3f {
    float x, y, z;
};

struct KGL_Vec4d {
    double x, y, w, h;
};

struct KGL_Vec4f {
    float x, y, w, h;
};

#endif